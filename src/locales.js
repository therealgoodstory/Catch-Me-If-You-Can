// UI languages. `flag` is a flag-icons code (same library as the result screen); `locale` feeds Intl.
const LANGS = [
  { code: "en", flag: "gb", label: "English", locale: "en" },
  { code: "ru", flag: "ru", label: "Русский", locale: "ru" },
  { code: "sr", flag: "rs", label: "Srpski", locale: "sr-Latn" },
  { code: "fr", flag: "fr", label: "Français", locale: "fr" },
  { code: "zh", flag: "cn", label: "中文", locale: "zh-Hans" },
  { code: "ko", flag: "kr", label: "한국어", locale: "ko" },
];

const STORAGE_LANG = "cmic.lang.v1";

function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_LANG);
    if (LANGS.some((l) => l.code === saved)) return saved;
  } catch {
    /* storage unavailable */
  }
  const pref = (navigator.languages || [navigator.language || "en"]).map((s) => s.slice(0, 2).toLowerCase());
  // Serbian and Croatian/Bosnian readers get the Serbian UI
  const hit = pref.map((p) => (p === "hr" || p === "bs" ? "sr" : p)).find((p) => LANGS.some((l) => l.code === p));
  return hit || "en";
}

currentLang = detectLang();
